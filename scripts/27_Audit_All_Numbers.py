def parse_chisq(path):
    p = Path(path)
    if not p.exists():
        return None, None
    import re
    t = p.read_text()
    m = re.search(r"X-squared\s*=\s*([\d.]+).*?p-value\s*=\s*([\d.e-]+)", t, re.S)
    return (float(m.group(1)), float(m.group(2))) if m else (None, None)


